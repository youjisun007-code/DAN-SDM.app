# 학생 발화 기준 전체 상담 길이. 프론트엔드(main.js)의 9턴 카운터/자동 종료 로직과 반드시 일치해야 한다.
SDM_TOTAL_TURNS = 9

# 이 턴 수부터 "조기 종료 및 성찰 작성" 버튼이 활성화된다. main.js의 EARLY_END_TURN과 반드시 일치해야 한다.
