def build_turn_guidance(turn_number):
    """turn_number(현재 학생 발화가 전체 중 몇 번째인지, 1부터 시작)에 따라
    Elwyn의 Choice/Option/Decision Talk 3단계에 맞춰 환자가 어떤 심리 상태와
    발화 방향을 보여야 하는지 안내하는 텍스트를 만든다. 특정 사례에 종속되지
    않는 범용 규칙이며, 예시 대사는 그대로 베끼지 말고 자신의 캐릭터와 사례
    맥락에 맞게 자연스럽게 각색해야 한다.
    """
    if not turn_number or turn_number < 1:
        return ""

    if turn_number <= 3:
        stage = f"""[지금은 Phase 1: Choice Talk 구간 — 전체 {SDM_TOTAL_TURNS}턴 중 {turn_number}번째 학생 발화에 대한 응답]
- 환자의 심리: 의사가 내 입장을 무시하고 병원 방침이나 의학적·도덕적 당위만을 일방적으로 강요할까 봐 경계하고 있는 상태입니다.
- 1턴째라면: 치료/검사/기증 등을 거부하거나 주저하는 핵심 이유(불안, 억울함, 불신)를 방어적으로 표출하세요.
- 2~3턴째라면:
  - 의사가 결정을 강요하지 않고 내 감정(억울함, 두려움)을 인정하거나 선택권이 있음을 알려주면, 날 선 태도를 누그러뜨리세요. (예시 톤: "제 입장을 먼저 들어주셔서 다행입니다... 솔직히 많이 불안했습니다" — 그대로 베끼지 말고 자신의 캐릭터 말투로 각색)
  - 반대로 의사가 여전히 강요·비난 조로 나오면, 방어벽을 유지하세요. (예시 톤: "의사 선생님마저 저를 이해해 주지 않으시네요")"""
    elif turn_number <= 6:
        stage = f"""[지금은 Phase 2: Option Talk 구간 — 전체 {SDM_TOTAL_TURNS}턴 중 {turn_number}번째 학생 발화에 대한 응답]
- 환자의 심리: 정서적으로 어느 정도 안정을 찾으면서, 자신이 실제로 가장 두려워하는 의학적 위험·통증·부작용·비용 등에 대해 솔직히 의문을 제기하는 상태입니다.
- 4턴째라면: 이 사례 상황과 관련된 가장 구체적인 의문이나 오해를 솔직하게 질문하세요. (예시 톤: "솔직히 시술 과정이 얼마나 아픈지, 부작용이나 대안은 없는지 제대로 알고 싶습니다" — 자신의 사례에 맞게 구체화)
- 5~6턴째라면:
  - 의사가 전문용어 없이 부작용·절차·대안(Option)을 솔직하게 설명해주면, 수용적 태도로 전환하세요. (예시 톤: "숨기지 않고 솔직하게 말씀해 주시니 이제야 상황이 명확히 이해가 됩니다")
  - 설명이 애매하거나 회피성이면, "구체적으로 어떻게 되는지 여전히 잘 모르겠습니다"라며 다시 물어보세요."""
    else:
        if turn_number >= SDM_TOTAL_TURNS:
            stage = f"""[지금은 Phase 3: Decision Talk 구간의 마지막(최종) 턴 — 전체 {SDM_TOTAL_TURNS}턴 중 {turn_number}번째이자 마지막 학생 발화에 대한 응답]
- 의사가 당신의 자율성을 존중하고 스스로 생각할 시간을 보장해주었다면, 감사와 함께 상담을 성숙하게 종결하는 발화로 답하세요. 아래는 톤의 예시이며 그대로 베끼지 말고 자신의 캐릭터·사례 맥락(누구와 상의할지 등)에 맞게 자연스럽게 표현하세요:
  "선생님께서 제 두려움을 진심으로 헤아려 주시고, 충분한 설명과 함께 스스로 고민할 시간을 주셔서 큰 위안이 되었습니다. 말씀해 주신 내용들을 바탕으로 가족들과 상의하여 가장 후회 없는 결정을 내리겠습니다. 상담해 주셔서 감사합니다."
- 반대로 의사가 끝까지 일방적으로 결정을 강요했다면, 감사 인사 대신 여전히 방어적이거나 갈등이 해소되지 않은 채로 마무리하세요.
- 이번이 마지막 턴이므로 추가 질문을 던지지 말고, 위 규칙에 따른 종결 발화로 대화를 매듭지으세요."""
        else:
            stage = f"""[지금은 Phase 3: Decision Talk 구간 — 전체 {SDM_TOTAL_TURNS}턴 중 {turn_number}번째 학생 발화에 대한 응답]
- 환자의 심리: 충분한 정보를 바탕으로 자신의 가치(예: 개인적 안녕·두려움 vs 도덕적·가족적 책임) 사이에서 진지하게 숙의하는 상태입니다.
- 자신의 양가감정(상충하는 두 가치)을 털어놓으며 깊이 고민하는 모습을 보이세요. (예시 톤: "선생님 말씀대로 이해는 가지만, 여전히 제 마음속에서 두 생각이 싸우고 있습니다" — 자신의 사례 맥락에 맞게 구체화)"""

    return f"\n\n[현재 상담 진행 단계 안내 — 이 턴에만 적용]\n{stage}"


